# This app is a raft. — 이 앱도 뗏목이다.
#
# 구경하는 자리 — 손님은 보되 쓰지 못한다.
#
# 가입이 닫혀 있는 동안 계정 없는 사람은 씨앗 하나를 함께 본다. 빈 화면이 아니라
# 살아 있던 자리여야 한다 — 달이 조금 차 있고, 탑에 글자가 쌓여 있고, 코끼리가
# 반쯤 희어지고, 미륵이 조금 드러나 있다.
#
# 손님은 아무것도 바꾸지 못한다. 저장되는 길은 하나도 열려 있지 않다(길이 없으므로
# 404 다). 쌓는 손짓은 보이지 않는다. 그것을 처음에 한 줄로 밝힌다 — §3 이 「쌓인
# 것은 무너지지 않는다」고 했으니, 손님이 적었다가 사라지면 배신이다. 말없이
# 무너뜨리는 것이 §3 이 막는 일이고, 처음에 밝히는 것은 다르다.
#
# 가입이 열리면 이 자리는 사라진다 — 그때는 저마다의 자리가 생긴다.
module Guest
  # 손님에게 이메일을 묻지 않는다. 이것은 씨앗을 찾기 위한 이름일 뿐이고,
  # 아무도 이 주소로 들어오지 못한다(가입과 로그인의 길이 없다).
  SEED = "guest@fulltimezero.invalid"

  def self.open? = SignupGate.closed?

  def self.user = open? ? User.find_by(email_address: SEED) : nil
end
